package com.legacy.legacytracker.tracking

import org.junit.Assert.assertEquals
import org.junit.Test
import java.io.File
import java.util.Locale
import kotlin.random.Random

/**
 * Writes what this engine's PathSampler and StopDetector do with fixed inputs to
 * `src/client/test/fixtures/tracking-vectors.json`, and fails when the committed file no longer
 * matches. The iOS engine replays the same file (`ios/RunnerTests/TrackingVectorsTests.swift`), so
 * the two copies cannot drift apart unnoticed.
 *
 * After an intended behaviour change: `UPDATE_TRACKING_VECTORS=1 ./gradlew :app:testDebugUnitTest`,
 * then port the change to Swift and run its tests.
 */
class TrackingVectorsTest {

    @Test
    fun committedVectorsMatchThisEngine() {
        val file = vectorsFile()
        val generated = generate()
        if (System.getenv("UPDATE_TRACKING_VECTORS") == "1" || !file.exists()) {
            file.parentFile?.mkdirs()
            file.writeText(generated)
            return
        }
        assertEquals(
            "${file.path} is stale: rerun with UPDATE_TRACKING_VECTORS=1 and update the Swift engine to match",
            file.readText(),
            generated,
        )
    }

    private fun vectorsFile(): File {
        val workingDir = checkNotNull(System.getProperty("user.dir")) { "user.dir is not set" }
        var dir: File? = File(workingDir).absoluteFile
        while (dir != null && !File(dir, "pubspec.yaml").exists()) dir = dir.parentFile
        checkNotNull(dir) { "src/client not found above $workingDir" }
        return File(dir, "test/fixtures/tracking-vectors.json")
    }

    // ── Cases ───────────────────────────────────────────────────────────────

    private fun generate(): String {
        val origin = Track.ORIGIN
        val sampler = listOf(
            run {
                val fixes = DriveSim.mixedDrive().map { round(it.gps) }
                samplerCase("mixed_drive", anchor = null, fixes = fixes, stop = fixes.last())
            },
            run {
                // Parked 400 m away when the trip was noticed: the sampler back-dates a departure.
                val anchor = round(origin.copy(time = 1_000_000L))
                val start = Track.offset(origin, 400.0, 0.0, 1_090_000L)
                val fixes = Track.line(start, bearingDeg = 70.0, speedMs = 14.0, seconds = 90).map(::round)
                samplerCase("departure_from_anchor", anchor = anchor, fixes = fixes, stop = null)
            },
        )
        val stop = listOf(
            run {
                val random = Random(7)
                val fixes = (0..300).map { s ->
                    round(
                        Track.offset(origin, random.nextDouble(-8.0, 8.0), random.nextDouble(-8.0, 8.0), 1_000_000L + s * 1000L)
                            .copy(accuracy = 10f, speed = 0.1f),
                    )
                }
                stopCase("parked", timeoutS = 300, fixes = fixes)
            },
            run {
                val random = Random(11)
                val fixes = (0..150).map { s ->
                    round(
                        Track.offset(origin, random.nextDouble(-5.0, 5.0), random.nextDouble(-5.0, 5.0), s * 1000L)
                            .copy(accuracy = 8f, speed = 0f),
                    )
                }
                stopCase("parked_still_timeout", timeoutS = 120, fixes = fixes)
            },
            run {
                // Traffic jam: 0.2 m/s for 10 minutes covers 120 m.
                val fixes = (0..600).map { s ->
                    round(Track.offset(origin, 0.2 * s, 0.0, s * 1000L).copy(accuracy = 5f, speed = 0.2f))
                }
                stopCase("slow_crawl", timeoutS = 300, fixes = fixes)
            },
            run {
                // Indoors: ±30 m wander reported with 50 m accuracy.
                val fixes = (0..300).map { s ->
                    val north = if (s % 2 == 0) 30.0 else -30.0
                    round(Track.offset(origin, north, 0.0, s * 1000L).copy(accuracy = 50f))
                }
                stopCase("indoor_wide_radius", timeoutS = 300, fixes = fixes)
            },
        )
        return buildString {
            append("{\n")
            append("  \"_about\": \"Generated by TrackingVectorsTest.kt, replayed by TrackingVectorsTests.swift. ")
            append("Fix: [time_ms, lat, lon, accuracy_m, speed_ms, bearing_deg]; stored: [time_ms, lat, lon, source].\",\n")
            append("  \"sampler\": [\n")
            append(sampler.joinToString(",\n"))
            append("\n  ],\n")
            append("  \"stop\": [\n")
            append(stop.joinToString(",\n"))
            append("\n  ]\n}\n")
        }
    }

    private fun samplerCase(name: String, anchor: Fix?, fixes: List<Fix>, stop: Fix?): String {
        val sampler = PathSampler()
        sampler.startTrip(anchor)
        val stored = ArrayList<PathSampler.Recorded>()
        for (fix in fixes) stored += sampler.offer(fix)
        stored += sampler.finishTrip(stop)
        return buildString {
            append("    {\n")
            append("      \"name\": \"$name\",\n")
            append("      \"anchor\": ${anchor?.let(::fixJson) ?: "null"},\n")
            append("      \"stop_at_last_fix\": ${stop != null},\n")
            append("      \"fixes\": [\n")
            append(fixes.joinToString(",\n") { "        " + fixJson(it) })
            append("\n      ],\n")
            append("      \"stored\": [\n")
            append(stored.joinToString(",\n") { "        [${it.fix.time}, ${deg(it.fix.lat)}, ${deg(it.fix.lon)}, \"${it.source}\"]" })
            append("\n      ]\n")
            append("    }")
        }
    }

    private fun stopCase(name: String, timeoutS: Int, fixes: List<Fix>): String {
        val detector = StopDetector()
        var index = -1
        var stop: Fix? = null
        for ((i, fix) in fixes.withIndex()) {
            stop = detector.offer(fix, timeoutS * 1000L)
            if (stop != null) {
                index = i
                break
            }
        }
        return buildString {
            append("    {\n")
            append("      \"name\": \"$name\",\n")
            append("      \"timeout_s\": $timeoutS,\n")
            append("      \"fixes\": [\n")
            append(fixes.joinToString(",\n") { "        " + fixJson(it) })
            append("\n      ],\n")
            append("      \"stop_index\": ${if (index >= 0) index else "null"},\n")
            append("      \"stop\": ${stop?.let { "[${it.time}, ${deg(it.lat)}, ${deg(it.lon)}]" } ?: "null"}\n")
            append("    }")
        }
    }

    // ── Formatting: inputs are rounded first, so both engines read exactly what this one ran ──

    private fun deg(v: Double) = String.format(Locale.ROOT, "%.7f", v)

    private fun metric(v: Float) = String.format(Locale.ROOT, "%.2f", v.toDouble())

    private fun round(fix: Fix) = Fix(
        time = fix.time,
        lat = deg(fix.lat).toDouble(),
        lon = deg(fix.lon).toDouble(),
        accuracy = metric(fix.accuracy).toFloat(),
        speed = metric(fix.speed).toFloat(),
        bearing = metric(fix.bearing).toFloat(),
    )

    private fun fixJson(fix: Fix) =
        "[${fix.time}, ${deg(fix.lat)}, ${deg(fix.lon)}, ${metric(fix.accuracy)}, ${metric(fix.speed)}, ${metric(fix.bearing)}]"
}
